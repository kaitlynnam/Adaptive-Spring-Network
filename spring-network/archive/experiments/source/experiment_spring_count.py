"""Quick nested-topology capacity test for piecewise-linear torque profiles."""

from pathlib import Path
import argparse
import copy
import csv
import json
import sys

import matplotlib.pyplot as plt
import numpy as np
from scipy.linalg import qr
from scipy.optimize import lsq_linear

PROJECT_ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(PROJECT_ROOT / "01_core_model"))
sys.path.insert(0, str(PROJECT_ROOT / "04_adaptive_learning"))

from adaptive_model import spring_torque_basis
from profile_generator import generate_profile_parameters, profile_torque
from topology_loader import build_network_from_topology


def expanded_springs(topology, count, rng):
    springs = copy.deepcopy(topology["springs"])
    existing = {tuple(sorted((s["node_a"], s["node_b"]))) for s in springs}
    limb2 = [n["name"] for n in topology["nodes"] if n["type"] == "limb2"]
    others = [n["name"] for n in topology["nodes"] if n["type"] != "limb2"]
    candidates = [(a, b) for a in limb2 for b in others if tuple(sorted((a, b))) not in existing]
    rng.shuffle(candidates)
    for a, b in candidates:
        if len(springs) >= count:
            break
        springs.append({"node_a": a, "node_b": b, "stiffness_k": 30.0})
    if len(springs) < count:
        raise ValueError(f"Could only construct {len(springs)} unique springs")
    return springs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profiles", type=int, default=200)
    parser.add_argument("--counts", type=int, nargs="+", default=[10, 20, 40, 60, 80])
    parser.add_argument("--seed", type=int, default=73)
    parser.add_argument("--output-name", default="spring_count_capacity_test")
    parser.add_argument(
        "--save-topologies",
        action="store_true",
        help="Save each tested topology under spring-network/topologies.",
    )
    args = parser.parse_args()

    topology_path = PROJECT_ROOT / "topologies" / "legacy" / "internal_fan_model.json"
    topology = json.loads(topology_path.read_text(encoding="utf-8"))
    rng = np.random.default_rng(args.seed)
    angles = np.linspace(-np.deg2rad(44.0), np.deg2rad(44.0), 181)
    profiles = generate_profile_parameters(rng, args.profiles)
    targets = np.vstack([profile_torque(angles, p) for p in profiles])
    target_rms = np.sqrt(np.mean(targets**2, axis=1))

    full40 = build_network_from_topology(topology)
    basis40 = spring_torque_basis(full40, angles, relax_internal=True)
    _, _, pivot = qr(basis40, mode="economic", pivoting=True)
    rows = []
    for count in args.counts:
        variant = copy.deepcopy(topology)
        if count < 40:
            keep = sorted(pivot[:count])
            variant["springs"] = [copy.deepcopy(topology["springs"][i]) for i in keep]
        elif count == 40:
            variant["springs"] = copy.deepcopy(topology["springs"])
        else:
            variant["springs"] = expanded_springs(topology, count, np.random.default_rng(args.seed + count))
        network = build_network_from_topology(variant)
        if args.save_topologies:
            variant["name"] = f"internal_fan_{count}_spring_model"
            variant["description"] = (
                f"Nested {count}-spring variant selected/generated by experiment_spring_count.py."
            )
            variant_path = PROJECT_ROOT / "topologies" / "legacy" / f"internal_fan_{count}_spring_model.json"
            variant_path.write_text(json.dumps(variant, indent=2) + "\n", encoding="utf-8")
            print(f"Saved topology: {variant_path}")
        basis = spring_torque_basis(network, angles, relax_internal=True)
        rmses = []
        offloads = []
        for target, zero_rmse in zip(targets, target_rms):
            fit = lsq_linear(basis, target, bounds=(1.0, 800.0), max_iter=300)
            rmse = float(np.sqrt(np.mean((basis @ fit.x - target) ** 2)))
            rmses.append(rmse)
            offloads.append(100.0 * (1.0 - rmse / max(float(zero_rmse), 1e-9)))
        rows.append(
            {
                "springs": count,
                "mean_rmse_nm": float(np.mean(rmses)),
                "median_rmse_nm": float(np.median(rmses)),
                "mean_torque_offload_pct": float(np.mean(offloads)),
                "median_torque_offload_pct": float(np.median(offloads)),
            }
        )
        print(
            f"{count:3d} springs | mean RMSE {rows[-1]['mean_rmse_nm']:.3f} Nm | "
            f"mean torque offload {rows[-1]['mean_torque_offload_pct']:.2f}%"
        )

    table = PROJECT_ROOT / "tables" / "legacy" / f"{args.output_name}.csv"
    plot = PROJECT_ROOT / "plots" / "legacy" / "dataset_examples" / f"{args.output_name}.png"
    table.parent.mkdir(parents=True, exist_ok=True)
    plot.parent.mkdir(parents=True, exist_ok=True)
    with table.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    fig, ax = plt.subplots(figsize=(7, 4.5))
    ax.plot([r["springs"] for r in rows], [r["mean_rmse_nm"] for r in rows], marker="o")
    ax.set_xlabel("Number of springs")
    ax.set_ylabel("Mean best-fit RMSE [Nm]")
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(plot, dpi=160)
    print(f"Saved table: {table}")
    print(f"Saved plot:  {plot}")


if __name__ == "__main__":
    main()
